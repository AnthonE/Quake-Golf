#!/usr/bin/env node
// Builds the sim for the Pentium III: build/game.wasm through tools/w2x86.mjs
// into build/x86/ (game.s for ELF, game-coff.s for nxdk, qg_sim.h, layout.h, font.h),
// then the freestanding Linux replay runner, build/x86/replay, and the Xbox
// game core's scripted test driver, build/x86/xbox-headless.
//
//   node tools/x86.mjs [--wasm build/game.wasm] [--no-bounds] [--no-runner]
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as layout from '../src/layout.mjs';
import { FONT } from '../client/font.mjs';
import { decode, translate, watNames } from './w2x86.mjs';
import { isMain } from './main.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(ROOT, 'build', 'x86');
export const RUNNER = join(OUT, 'replay');
export const HEADLESS = join(OUT, 'xbox-headless');

export function layoutHeader() {
  const lines = ['// Generated by tools/x86.mjs from src/layout.mjs. Do not edit.', '#ifndef QG_LAYOUT_H', '#define QG_LAYOUT_H'];
  for (const [k, v] of Object.entries(layout)) {
    if (typeof v === 'number' && Number.isInteger(v)) lines.push(`#define QG_${k} ${v < 0 ? v : `${v}u`}`);
  }
  for (const [k, v] of Object.entries(layout.PHYS)) lines.push(`#define QG_${k} ${Number(v)}f`);
  lines.push('#endif', '');
  return lines.join('\n');
}

// The browser HUD's 3x5 font (client/font.mjs), ASCII 32-95, top-left pixel in bit 14.
export function fontHeader() {
  const rows = [];
  for (let i = 0; i < FONT.length; i += 8) rows.push(`  ${Array.from(FONT.slice(i, i + 8), (g) => `0x${g.toString(16).padStart(4, '0')}`).join(', ')},`);
  return ['// Generated by tools/x86.mjs from client/font.mjs. Do not edit.', '#ifndef QG_FONT_H', '#define QG_FONT_H',
    '#include <stdint.h>', 'static const uint16_t QG_FONT[64] = {', ...rows, '};', '#endif', ''].join('\n');
}

// clang, as the runner and CI need it: 32-bit, Pentium III, no libc.
export const CFLAGS = ['-m32', '-march=pentium3', '-O2', '-ffreestanding', '-fno-builtin', '-nostdlib', '-static',
  '-fno-pic', '-fno-stack-protector', '-fno-asynchronous-unwind-tables', '-mstackrealign', '-fuse-ld=lld',
  '-Wall', '-Wno-unused-function'];

export function buildX86({ wasm = join(ROOT, 'build', 'game.wasm'), bounds = true, runner = true, out = OUT } = {}) {
  if (!existsSync(wasm)) execFileSync(process.execPath, [join(ROOT, 'tools', 'asm.mjs')], { stdio: 'inherit' });
  mkdirSync(out, { recursive: true });
  const bin = readFileSync(wasm);
  const wat = wasm.replace(/\.wasm$/, '.wat');
  let names = existsSync(wat) ? watNames(readFileSync(wat, 'utf8')) : [];
  if (names.length !== decode(bin).funcs.length) names = []; // cosmetic only: never guess
  const prefix = createHash('sha256').update(bin).digest().subarray(0, 8);
  const elf = translate(bin, { target: 'elf', bounds, names, prefix });
  writeFileSync(join(out, 'game.s'), elf.asm);
  writeFileSync(join(out, 'game-coff.s'), translate(bin, { target: 'coff', bounds, names, prefix }).asm);
  writeFileSync(join(out, 'qg_sim.h'), elf.header);
  writeFileSync(join(out, 'font.h'), fontHeader());
  writeFileSync(join(out, 'layout.h'), layoutHeader());
  if (runner) {
    const native = join(ROOT, 'harness', 'native');
    execFileSync('clang', [...CFLAGS, `-I${out}`, join(native, 'replay.c'), join(out, 'game.s'), '-o', join(out, 'replay')], { stdio: 'inherit' });
    // the Xbox game core with scripted controllers (xbox/headless.c)
    execFileSync('clang', [...CFLAGS, `-I${out}`, `-I${native}`, `-I${join(ROOT, 'xbox')}`,
      ...['headless.c', 'game.c', 'online.c', 'inflate.c'].map((f) => join(ROOT, 'xbox', f)), join(out, 'game.s'), '-o', join(out, 'xbox-headless')], { stdio: 'inherit' });
  }
  return { lines: elf.asm.split('\n').length, counts: elf.counts };
}

if (isMain(import.meta.url)) {
  const argv = process.argv.slice(2);
  const i = argv.indexOf('--wasm');
  const r = buildX86({ wasm: i >= 0 ? resolve(argv[i + 1]) : undefined, bounds: !argv.includes('--no-bounds'), runner: !argv.includes('--no-runner') });
  console.log(`build/x86/game.s ${r.lines} lines${argv.includes('--no-runner') ? '' : ', build/x86/replay, build/x86/xbox-headless'}`);
}
