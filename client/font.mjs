export const FONT = Uint32Array.from(GLYPHS.trim().split(/\s*[|\n]\s*/), (g) => {
  const bits = g.replace(/\s/g, '');
  let v = 0;
  for (const c of bits) v = (v << 1) | (c === '#' ? 1 : 0);
  return v;
});

if (FONT.length !== 64) throw new Error(`font has ${FONT.length} glyphs, not 64`);

// Text into HUD cells: the character in the low 8 bits, a palette colour in bits 8-10.
export const C = { WHITE: 0, YELLOW: 1, RED: 2, GREEN: 3, GREY: 4, CYAN: 5, ORANGE: 6, PURPLE: 7 };
export function put(cells, cols, x, y, text, color = C.WHITE) {
  const rows = cells.length / cols;
  if (y < 0 || y >= rows) return;
  text = String(text).toUpperCase();
  for (let i = 0; i < text.length; i++) {
    const cx = x + i;
    if (cx < 0 || cx >= cols) continue;
    cells[y * cols + cx] = (text.charCodeAt(i) & 255) | (color << 8);
  }
}
